"""Fixed shapes and explicit masks for JIT-compiled steps."""

import numpy as np


def fixed_batches(data, batch_size, *, indices=None, drop_last=False):
    """Yield fixed-shape NumPy batches with explicit validity masks.

    Args:
        data: Nonempty mapping of arrays sharing the same sample dimension.
            The reserved key ``mask`` must not be supplied.
        batch_size: Positive number of rows in each emitted batch.
        indices: Optional one-dimensional integer selection/order of sample rows.
        drop_last: Discard incomplete final batches instead of padding them.

    Yields:
        Mapping of data arrays with leading dimension ``batch_size`` plus a
        boolean ``mask``. Padded rows repeat the final selected observation and
        have mask value False, so reducers must honor the mask.

    Raises:
        ValueError: If sizes, sample dimensions or selected indices are invalid.
    """
    if not isinstance(batch_size, int) or batch_size < 1:
        raise ValueError("batch_size must be positive")
    if not data:
        raise ValueError("data must contain arrays")
    arrays = {key: np.asarray(value) for key, value in data.items()}
    if any(value.ndim == 0 for value in arrays.values()):
        raise ValueError("data arrays require a sample dimension")
    size = len(next(iter(arrays.values())))
    if size < 1 or any(
        value.ndim == 0 or len(value) != size for value in arrays.values()
    ):
        raise ValueError("data arrays must share a nonempty sample dimension")
    if "mask" in arrays:
        raise ValueError("mask is generated by fixed_batches")
    indices = np.arange(size) if indices is None else np.asarray(indices)
    if (
        indices.ndim != 1
        or not np.issubdtype(indices.dtype, np.integer)
        or np.any(indices < 0)
        or np.any(indices >= size)
    ):
        raise ValueError("invalid batch indices")
    if drop_last:
        indices = indices[: (len(indices) // batch_size) * batch_size]
    for start in range(0, len(indices), batch_size):
        selected = indices[start : start + batch_size]
        count = len(selected)
        padded = np.pad(selected, (0, batch_size - count), mode="edge")
        yield {
            **{key: value[padded] for key, value in arrays.items()},
            "mask": np.arange(batch_size) < count,
        }


def trimmed_batches(values, batch_size):
    """Reshape a feature matrix into complete fixed-size batches.

    Args:
        values: Two-dimensional array of shape ``(samples, features)``.
        batch_size: Number of observations in each complete batch.

    Returns:
        Array of shape ``(samples // batch_size, batch_size, features)``.
        Incomplete trailing rows are discarded; no padding or mask is added.
    """
    trimmed = values[: (values.shape[0] // batch_size) * batch_size]
    return trimmed.reshape((-1, batch_size, values.shape[1]))
